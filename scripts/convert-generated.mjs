#!/usr/bin/env node
// Converts the committed C++ SDK registries into TypeScript modules.
//
//   ../runtime/ApiMetadata.generated.inc     -> src/runtime/ApiMetadata.generated.ts
//   ../runtime/SdkDefinitions.generated.inc  -> src/runtime/SdkDefinitions.generated.ts
//
// The .inc files remain the source of truth; they are produced from the SDK
// headers by ../tools/generate_*.py. Re-run this script after regenerating them.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const webRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cppRuntime = path.resolve(webRoot, '..', 'runtime');
const outDir = path.join(webRoot, 'src', 'runtime');

// Parses the brace initializers of one `name[] = { ... };` / `name = { ... };`
// declaration into nested arrays. Leaves are {kind, text, value}.
function parseInitializer(source, declarationName) {
  const start = source.indexOf(declarationName);
  if (start < 0) throw new Error(`missing ${declarationName}`);
  let i = source.indexOf('{', start);
  const tokens = [];
  const end = source.indexOf('};', i);
  while (i <= end) {
    const ch = source[i];
    if (/\s/.test(ch)) {
      ++i;
      continue;
    }
    if (ch === '{' || ch === '}' || ch === ',') {
      tokens.push({ kind: ch });
      ++i;
      continue;
    }
    if (ch === '"') {
      let j = i + 1;
      let text = '';
      while (source[j] !== '"') {
        if (source[j] === '\\') {
          const next = source[j + 1];
          const escapes = { n: '\n', t: '\t', r: '\r', '\\': '\\', '"': '"', "'": "'", 0: '\0' };
          if (!(next in escapes)) throw new Error(`unsupported escape \\${next}`);
          text += escapes[next];
          j += 2;
        } else {
          text += source[j++];
        }
      }
      tokens.push({ kind: 'string', value: text });
      i = j + 1;
      continue;
    }
    const m = /^(true|false|[-+]?(?:\d+\.?\d*(?:[eE][-+]?\d+)?|\.\d+(?:[eE][-+]?\d+)?))/.exec(source.slice(i));
    if (!m) throw new Error(`unexpected input near: ${source.slice(i, i + 40)}`);
    const text = m[1];
    if (text === 'true' || text === 'false') tokens.push({ kind: 'bool', value: text === 'true' });
    else tokens.push({ kind: 'number', text, value: Number(text) });
    i += text.length;
  }

  let pos = 0;
  function parseValue() {
    const t = tokens[pos];
    if (t.kind === '{') {
      ++pos;
      const items = [];
      while (tokens[pos].kind !== '}') {
        items.push(parseValue());
        if (tokens[pos].kind === ',') ++pos;
      }
      ++pos;
      return items;
    }
    ++pos;
    return t;
  }
  return parseValue();
}

function header(inc) {
  return (
    `// Generated by scripts/convert-generated.mjs from ../runtime/${inc}; do not hand-edit.\n` +
    '// Regenerate the .inc from the SDK headers (see ../runtime/BUILTIN_CONSTANTS.md), then run `npm run generate`.\n'
  );
}

function convertApiMetadata() {
  const inc = 'ApiMetadata.generated.inc';
  const source = fs.readFileSync(path.join(cppRuntime, inc), 'utf8');
  const rows = parseInitializer(source, 'kNativeApiSignatures');
  const lines = [
    header(inc),
    "import type { ApiSignatureMetadata } from './ApiMetadata';",
    '',
    'export const kNativeApiSignatures: readonly ApiSignatureMetadata[] = [',
  ];
  for (const [name, returnType, sourceHeader, required, parameters] of rows) {
    const params = parameters.map(
      ([pName, pType, pDefault]) =>
        `{ name: ${JSON.stringify(pName.value)}, type: ${JSON.stringify(pType.value)}, defaultValue: ${JSON.stringify(pDefault.value)} }`,
    );
    lines.push(
      `  { name: ${JSON.stringify(name.value)}, returnType: ${JSON.stringify(returnType.value)}, ` +
        `sourceHeader: ${JSON.stringify(sourceHeader.value)}, requiredParameterCount: ${required.text}, ` +
        `parameters: [${params.join(', ')}] },`,
    );
  }
  lines.push('];', '');
  fs.writeFileSync(path.join(outDir, 'ApiMetadata.generated.ts'), lines.join('\n'));
  return rows.length;
}

function convertSdkDefinitions() {
  const inc = 'SdkDefinitions.generated.inc';
  const source = fs.readFileSync(path.join(cppRuntime, inc), 'utf8');
  const constants = parseInitializer(source, 'kSdkConstants');
  const types = parseInitializer(source, 'kSdkTypes');
  const lines = [
    header(inc),
    "import type { SdkConstantDefinition, SdkTypeDefinition } from './SdkDefinitions';",
    '',
    'export const kSdkConstants: readonly SdkConstantDefinition[] = [',
  ];
  for (const [name, value, integer] of constants)
    lines.push(`  { name: ${JSON.stringify(name.value)}, value: ${value.text}, integer: ${integer.value} },`);
  lines.push('];', '', 'export const kSdkTypes: readonly SdkTypeDefinition[] = [');
  for (const [name, baseType, extent] of types)
    lines.push(
      `  { name: ${JSON.stringify(name.value)}, baseType: ${JSON.stringify(baseType.value)}, arrayExtent: ${extent.text} },`,
    );
  lines.push('];', '');
  fs.writeFileSync(path.join(outDir, 'SdkDefinitions.generated.ts'), lines.join('\n'));
  return [constants.length, types.length];
}

const signatures = convertApiMetadata();
const [constants, types] = convertSdkDefinitions();
console.log(`converted ${signatures} API signatures, ${constants} SDK constants, ${types} SDK types`);
